import json
from pathlib import Path
import re
import shlex
import subprocess
import tempfile
import unittest


REPOSITORY = Path(__file__).resolve().parents[3]
EVALUATION = REPOSITORY / "home" / "desktop" / "tests" / "evaluate.nix"


class HyprlandConfigBackupTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        evaluation = subprocess.run(
            ["nix", "eval", "--impure", "--json", "--file", str(EVALUATION)],
            cwd=REPOSITORY,
            check=True,
            capture_output=True,
            text=True,
            timeout=120,
        )
        cls.backup_script = json.loads(evaluation.stdout)["hyprland"]["hyprlandBackupScript"]

    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)

        self.config = Path(self.directory.name) / "config with spaces" / "hyprland.conf"
        self.config.parent.mkdir()

    def run_backup(self, dry_run=False):
        script = re.sub(
            r"^hyprland_config=.*$",
            f"hyprland_config={shlex.quote(str(self.config))}",
            self.backup_script,
            count=1,
            flags=re.MULTILINE,
        )
        runner = 'run() { "$@"; }'
        if dry_run:
            runner = 'run() { printf "%s\\n" "$*"; }'

        subprocess.run(
            ["bash", "-euo", "pipefail", "-c", runner + "\n" + script],
            check=True,
            capture_output=True,
            text=True,
            timeout=10,
        )

    def backups(self):
        return list(self.config.parent.glob("hyprland.conf.unmanaged.*"))

    def test_autogenerated_stub_is_backed_up_before_replacement(self):
        contents = "autogenerated = 1\nbind = SUPER, T, exec, kitty\n"
        self.config.write_text(contents)

        self.run_backup()

        self.assertEqual(self.config.read_text(), contents)
        backups = self.backups()
        self.assertEqual(len(backups), 1)
        self.assertEqual(backups[0].read_text(), contents)

    def test_custom_unmanaged_config_is_preserved(self):
        contents = "monitor = ,preferred,auto,1\n"
        self.config.write_text(contents)
        self.config.chmod(0o600)

        self.run_backup()

        backup = self.backups()[0]
        self.assertEqual(backup.read_text(), contents)
        self.assertEqual(backup.stat().st_mode & 0o777, 0o600)

    def test_managed_symlink_is_not_backed_up(self):
        source = self.config.parent / "managed.conf"
        source.write_text("monitor = ,preferred,auto,1\n")
        self.config.symlink_to(source)

        self.run_backup()

        self.assertEqual(self.backups(), [])
        self.assertTrue(self.config.is_symlink())

    def test_missing_config_needs_no_backup(self):
        self.run_backup()

        self.assertEqual(self.backups(), [])
        self.assertFalse(self.config.exists())

    def test_repeated_backups_do_not_overwrite_earlier_config(self):
        self.config.write_text("autogenerated = 1\n")
        self.run_backup()
        self.config.write_text("monitor = ,preferred,auto,1\n")
        self.run_backup()

        self.assertEqual(len(self.backups()), 2)
        self.assertEqual(
            {backup.read_text() for backup in self.backups()},
            {"autogenerated = 1\n", "monitor = ,preferred,auto,1\n"},
        )

    def test_dry_run_does_not_write_a_backup(self):
        self.config.write_text("autogenerated = 1\n")

        self.run_backup(dry_run=True)

        self.assertEqual(self.backups(), [])


if __name__ == "__main__":
    unittest.main()
